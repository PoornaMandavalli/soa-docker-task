// src/components/PetList.jsx
// Displays all registered pets in a Bootstrap table.
// Supports Edit and Delete actions.

import React from 'react';

function PetList({ pets, loading, onEdit, onDelete, deleteLoadingId }) {

  // ── Loading spinner (initial fetch) ──────────────────────────────────────
  if (loading) {
    return (
      <div className="pet-card">
        <div className="section-title">
          <i className="bi bi-list-ul"></i>
          All Pets
        </div>
        <div className="text-center py-5">
          <div
            className="spinner-border"
            role="status"
            style={{ color: 'var(--primary)', width: '2.5rem', height: '2.5rem' }}
          >
            <span className="visually-hidden">Loading...</span>
          </div>
          <p className="mt-3 text-muted" style={{ fontSize: '0.9rem' }}>
            Fetching pets from the server...
          </p>
        </div>
      </div>
    );
  }

  return (
    <div className="pet-card">

      {/* Section title */}
      <div className="section-title">
        <i className="bi bi-list-ul"></i>
        All Pets
        <span
          className="ms-auto"
          style={{
            fontSize: '0.78rem',
            fontWeight: 600,
            color: 'var(--text-muted)',
            background: 'var(--bg)',
            padding: '3px 10px',
            borderRadius: '20px',
            border: '1px solid var(--border)'
          }}
        >
          {pets.length} record{pets.length !== 1 ? 's' : ''}
        </span>
      </div>

      {/* Empty state */}
      {pets.length === 0 ? (
        <div className="empty-state">
          <i className="bi bi-inbox"></i>
          <h6>No pets registered yet</h6>
          <p style={{ fontSize: '0.875rem' }}>
            Use the form above to add your first pet.
          </p>
        </div>
      ) : (
        <div className="table-responsive">
          <table className="pets-table">
            <thead>
              <tr>
                <th>#ID</th>
                <th>Pet Name</th>
                <th>Species</th>
                <th>Age (Yrs)</th>
                <th>Vaccinated</th>
                <th>Actions</th>
              </tr>
            </thead>
            <tbody>
              {pets.map((pet) => (
                <tr key={pet.id}>

                  {/* ID — auto-generated by backend */}
                  <td>
                    <span className="id-badge">{pet.id}</span>
                  </td>

                  {/* Pet Name */}
                  <td style={{ fontWeight: 600 }}>{pet.petName}</td>

                  {/* Species */}
                  <td style={{ color: 'var(--text-muted)' }}>{pet.species}</td>

                  {/* Age */}
                  <td>{pet.ageYears} yr{pet.ageYears !== 1 ? 's' : ''}</td>

                  {/* Vaccination Status */}
                  <td>
                    {pet.vaccinated ? (
                      <span className="badge-vaccinated">
                        <i className="bi bi-check-circle-fill"></i> Yes
                      </span>
                    ) : (
                      <span className="badge-not-vaccinated">
                        <i className="bi bi-x-circle-fill"></i> No
                      </span>
                    )}
                  </td>

                  {/* Actions */}
                  <td>
                    <div className="d-flex gap-1">

                      {/* Edit button */}
                      <button
                        className="btn-action btn-action-edit"
                        title="Edit pet"
                        onClick={() => onEdit(pet)}
                      >
                        <i className="bi bi-pencil-fill"></i>
                      </button>

                      {/* Delete button */}
                      <button
                        className="btn-action btn-action-delete"
                        title="Delete pet"
                        onClick={() => onDelete(pet.id)}
                        disabled={deleteLoadingId === pet.id}
                      >
                        {deleteLoadingId === pet.id ? (
                          <span
                            className="spinner-border spinner-border-sm"
                            role="status"
                          ></span>
                        ) : (
                          <i className="bi bi-trash-fill"></i>
                        )}
                      </button>

                    </div>
                  </td>

                </tr>
              ))}
            </tbody>
          </table>
        </div>
      )}
    </div>
  );
}

export default PetList;
